import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const src=readFileSync(new URL('../src/import/catalogCsv.ts',import.meta.url),'utf8');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const {parseCatalog,CSV_TEMPLATE}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const model=parseCatalog(CSV_TEMPLATE);
assert.equal(model.issues.length,0);
assert.equal(model.rows[0].sku,'000123');
assert.equal(model.rows[0].barcode,'0123456789012');
const q=parseCatalog('\ufeffsku;nome;descrição;estoque_minimo;estoque_maximo;codigo_barras\r\n0001;"Produto; A";"linha 1\r\nlinha ""2""";1,5;2,75;00000001\r\n0002;Outro;;;;\r\n');
assert.equal(q.issues.length,0);
assert.equal(q.rows[0].description,'linha 1\r\nlinha "2"');
assert.equal(q.rows[0].min_stock,1.5);
assert.equal(q.rows[0].max_stock,2.75);
assert.equal(q.rows[1].line,4);
assert.equal(q.rows[1].barcode,null);
assert.equal(parseCatalog('sku,name,min_stock\nA,"A, B",2.5\n').rows[0].name,'A, B');
assert.throws(()=>parseCatalog('sku;nome;saldo\na;A;42'),/Cabeçalho/);
assert.throws(()=>parseCatalog('sku;name;nome\na;A;B'),/Cabeçalho/);
assert.throws(()=>parseCatalog('sku;nome\na;"não fechado'),/fechado/);
assert.throws(()=>parseCatalog('sku;nome\na;"A"b'),/após aspas/);
assert.ok(parseCatalog('sku;nome\na;A\nA;B').issues.length>=2);
assert.ok(parseCatalog('sku;nome;barcode\na;A;001\nb;B;001').issues.length>=2);
assert.equal(parseCatalog('sku;nome;min_stock\na;A;-2').issues.length,1);
assert.equal(parseCatalog('sku;nome;min_stock;max_stock\na;A;5;4').issues.length,1);
assert.equal(parseCatalog('sku;nome;min_stock\na;A;1e4').issues.length,1);
assert.equal(parseCatalog('sku;nome\na;A;extra').issues.length,1);
const bulk='sku;nome;codigo_barras\n'+Array.from({length:3000},(_,i)=>String(i+1).padStart(6,'0')+';Produto '+i+';'+String(i+1).padStart(13,'0')).join('\n');
const parsed=parseCatalog(bulk);
assert.equal(parsed.issues.length,0);
assert.equal(parsed.rows.length,3000);
assert.equal(parsed.rows.at(-1).barcode,'0000000003000');
assert.throws(()=>parseCatalog('sku;nome\n'+Array.from({length:5001},(_,i)=>i+';A').join('\n')),/5.000/);
console.log('Round 11 CSV: encoding, quotes, multiline, decimals, leading zeros, column validation, duplicates and 3000 rows passed.');
