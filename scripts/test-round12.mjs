import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const url=(path,replace={})=>{
  let source=readFileSync(new URL(path,import.meta.url),'utf8');
  for(const [a,b] of Object.entries(replace))source=source.replaceAll(a,b);
  const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
  return 'data:text/javascript;base64,'+Buffer.from(js).toString('base64');
};
const parser=url('../src/import/catalogCsv.ts');
const {readSource,suggestMapping,mappedCatalog,mappedStock,validateMapping}=await import(url('../src/integrations/erpCsv.ts',{'../import/catalogCsv':parser}));
const sample=readSource('\ufeffCódigo Produto;Descrição Produto;EAN;Grupo;Unidade;Saldo Físico;Preço\n00023;"Parafuso; inox";0001234567890;Fixação;un;5,25;9,99\n00024;Porca;0000123456789;Fixação;un;0;4,00');
const cm=suggestMapping(sample,'catalog');
assert.equal(cm.sku,0);assert.equal(cm.name,1);assert.equal(cm.barcode,2);assert.equal(cm.unit_base,4);
const c=mappedCatalog(sample,cm);
assert.equal(c.issues.length,0);assert.equal(c.rows.length,2);
assert.equal(c.rows[0].sku,'00023');assert.equal(c.rows[0].barcode,'0001234567890');
assert.equal(c.rows[0].name,'Parafuso; inox');assert.equal(c.rows[0].min_stock,0);
assert.equal('quantity' in c.rows[0],false);
const sm=suggestMapping(sample,'stock');assert.equal(sm.quantity,5);
const s=mappedStock(sample,sm);
assert.equal(s.issues.length,0);assert.equal(s.rows[0].quantity,'5.25');assert.equal(s.rows[1].quantity,'0');
assert.throws(()=>validateMapping(sample,'stock',{sku:0,unit_base:0,quantity:5}),/distinta/);
assert.throws(()=>validateMapping(sample,'stock',{sku:0,quantity:5}),/Selecione/);
assert.throws(()=>readSource('SKU;sku\nx;y'),/duplicado/);
assert.throws(()=>readSource('sku;saldo\nx;1;3'),/colunas/);
const ambiguous=readSource('SKU;Código Produto;Produto\nA;B;C');assert.equal(suggestMapping(ambiguous,'catalog').sku,undefined);
const invalid=readSource('sku;unidade;saldo\n001;un;\n002;un;-5\n003;un;1.234,5\n004;un;1e5\n005;;1\n006;un;1,1234567\n007;un;0');
assert.equal(mappedStock(invalid,suggestMapping(invalid,'stock')).issues.length,6);
const duplicate=readSource('sku;unidade;saldo\na;un;1\nA;un;2');
assert.equal(mappedStock(duplicate,suggestMapping(duplicate,'stock')).issues.length,2);
const multiline=readSource('ID;Produto;Detalhe\n001;"A\nB";OK\n002;;X\n003;Outro;OK');
const mc=mappedCatalog(multiline,{sku:0,name:1,description:2});
assert.equal(mc.rows[0].line,2);assert.equal(mc.rows[1].line,5);assert.equal(mc.issues[0].line,4);
const bulk=readSource('codigo;unidade;saldo\n'+Array.from({length:3000},(_,i)=>String(i+1).padStart(6,'0')+';un;1,50').join('\n'));
const out=mappedStock(bulk,suggestMapping(bulk,'stock'));assert.equal(out.issues.length,0);assert.equal(out.rows.length,3000);
assert.equal(out.rows.at(-1).sku,'003000');assert.equal(out.rows.at(-1).quantity,'1.50');
console.log('Round 12 ERP CSV: mapping, ambiguity, source line numbers, decimal precision, leading zeros, duplicates, 3000 rows and catalog isolation passed.');
